// One-time lifecycle migration from the user's "波更新" revision.
// Preserve the original renderer/shaders; Vue owns mounting and disposal.
const { execFileSync } = require('node:child_process')
const fs = require('node:fs')
const read = file => execFileSync('git', ['show', `8ba23de:companywebsite/src/components/${file}`], { encoding: 'utf8', maxBuffer: 4 * 1024 * 1024 }).replace(/\r\n/g, '\n')
const sphere = read('InteractiveSphere.tsx')
let body = sphere.slice(sphere.indexOf('        const host = hostRef.current'), sphere.indexOf('    }, [contextVersion])'))
body = body.replace('        const host = hostRef.current\n        const canvas = canvasRef.current\n', '')
body = body.replace('const contextRestored = () => setContextVersion(value => value + 1)', 'const contextRestored = () => onContextRestored()')
body = body.replace('motion.matches ? (progress >= 0.5 ? 1 : 0)', 'motion.matches ? 0')
body = body.split('\n').map(line => line.startsWith('    ') ? line.slice(4) : line).join('\n')
const imports = sphere.slice(sphere.indexOf('import {\n'), sphere.indexOf("import './InteractiveSphere.css'"))
  .replace("from './sphereShaders'", "from './sphereTheme'")
fs.mkdirSync('src/visuals', { recursive: true })
fs.writeFileSync('src/visuals/mountSphere.ts', '// Renderer preserved from commit 8ba23de (波更新), with Vue lifecycle integration.\n' + imports + '\nexport function mountSphere(host: HTMLDivElement, canvas: HTMLCanvasElement, onContextRestored: () => void) {\n' + body + '\n}\n')
for (const name of ['sphereShaders.ts', 'sphereOrbits.ts']) fs.writeFileSync('src/visuals/' + name, read(name))
const wave = read('DotWaveBackground.tsx')
let waveBody = wave.slice(wave.indexOf('        const canvas = canvasRef.current'), wave.indexOf('    }, [])'))
waveBody = waveBody.replace('        const canvas = canvasRef.current\n        if (!canvas) return\n', '')
waveBody = waveBody.replace('rgba(134, 187, 198, ${opacity})', 'rgba(78, 125, 151, ${opacity})')
waveBody = waveBody.split('\n').map(line => line.startsWith('    ') ? line.slice(4) : line).join('\n')
const settings = wave.slice(wave.indexOf('// 點狀波浪設定'), wave.indexOf('const DotWaveBackground ='))
fs.writeFileSync('src/visuals/mountDotWave.ts', '// Perspective wave preserved from commit 8ba23de (波更新).\n' + settings + '\nexport function mountDotWave(canvas: HTMLCanvasElement) {\n' + waveBody + '\n}\n')
console.log('Ported the original sphere, orbit, shader, and dot-wave implementations from 8ba23de.')
